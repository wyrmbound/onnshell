# Runs ON the box, fed through stdin: adb shell sh < scripts/probe.sh
# Read only. Prints docs/DEVICE.md to stdout. Nothing is written on the box.
EVPROBE=/data/local/tmp/onnshell-evprobe

sec() { printf '\n## %s\n\n' "$1"; }
run() { printf '`%s`\n\n```\n' "$1"; sh -c "$1" 2>&1; printf '```\n\n'; }

# Facts for the summary
ACCOUNTS=$(dumpsys account 2>/dev/null | grep -m1 'Accounts:' | sed 's/^ *//')
HOME_NOW=$(cmd package resolve-activity --brief -a android.intent.action.MAIN -c android.intent.category.HOME | tail -n 1)
VK_VER=$(pm list features | grep 'vulkan.version=' | cut -d= -f2)
if [ -n "$VK_VER" ]; then
  VULKAN="yes, $((VK_VER >> 22)).$(((VK_VER >> 12) & 1023)).$((VK_VER & 4095)) (feature version $VK_VER)"
else
  VULKAN="no"
fi
GLES=$(dumpsys SurfaceFlinger 2>/dev/null | grep -m1 '^GLES:')
# "ip link show eth0" is denied to shell on this firmware, the full dump is allowed
ETH_LINK=$(ip -o link | grep ' eth0:' | grep -o 'NO-CARRIER' || echo carrier)
ETH_IP=$(ip -o -4 addr | awk '$2=="eth0" {print $4}')
WLAN_IP=$(ip -o -4 addr | awk '$2=="wlan0" {print $4}')
ADB_WIFI=$(settings get global adb_wifi_enabled)
DEFAULT_NET=$(dumpsys connectivity 2>/dev/null | grep -m1 -o 'ni{[A-Z]* [A-Z]*' | tr -d '{' | cut -c3-)

if [ -n "$ETH_IP" ] && [ -n "$WLAN_IP" ]; then BOTH="yes, both have an address now"
elif [ -n "$ETH_IP" ] || [ -n "$WLAN_IP" ]; then BOTH="not tested, only one interface is up now"
else BOTH="not tested, no interface has an address"; fi

if [ -n "$ETH_IP" ] && [ -z "$WLAN_IP" ] && [ "$ADB_WIFI" = "1" ]; then WD_ETH="yes, enabled with Ethernet only"
elif [ -n "$ETH_IP" ] && [ -z "$WLAN_IP" ]; then WD_ETH="not tested, on Ethernet only but wireless debugging is off (adb_wifi_enabled=$ADB_WIFI)"
else WD_ETH="not tested, box is not on Ethernet only (eth0: ${ETH_IP:-$ETH_LINK}, wlan0: ${WLAN_IP:-none})"; fi

if [ -x "$EVPROBE" ]; then EV=$("$EVPROBE" 2>&1); else EV="evprobe=not_pushed"; fi
ev() { echo "$EV" | grep -m1 "^$1=" | cut -d= -f2-; }
TP_NODE=$(ev node)
if [ "$(ev touchpad)" = "found" ]; then
  TP="yes, $TP_NODE ($(ev name)), open=$(ev open), read=$(ev read)"
  TP_PERM=$(ls -l "$TP_NODE")
  GRAB="$(ev grab), exclusive=$(ev grab_exclusive), release=$(ev release)"
else
  TP="no ($(ev touchpad)$(ev evprobe))"; TP_PERM="n/a"; GRAB="not tested, no touchpad node"
fi

cat <<EOF
# DEVICE.md

Generated by \`scripts/discover\` on $(date '+%Y-%m-%d %H:%M %Z') (box clock). Read only, nothing was changed on the box.

## Summary

| Check | Result |
|---|---|
| Model | $(getprop ro.product.model) ($(getprop ro.product.device)) |
| SoC | $(getprop ro.soc.manufacturer) $(getprop ro.soc.model), platform $(getprop ro.board.platform) |
| Android | $(getprop ro.build.version.release) (SDK $(getprop ro.build.version.sdk)), patch $(getprop ro.build.version.security_patch) |
| Fingerprint | \`$(getprop ro.build.fingerprint)\` |
| Accounts | $ACCOUNTS |
| Current HOME | \`$HOME_NOW\` |
| GLES | $GLES |
| Vulkan | $VULKAN |
| Default network | $DEFAULT_NET |
| eth0 | ${ETH_IP:-no address} ($ETH_LINK) |
| wlan0 | ${WLAN_IP:-no address} |
| Wi-Fi and Ethernet up together | $BOTH |
| Wireless debugging on Ethernet only | $WD_ETH |
| Wireless debugging setting | adb_wifi_enabled=$ADB_WIFI, adb tcp port $(getprop service.adb.tcp.port) |
| DS4 touchpad node | $TP |
| Touchpad node permissions | \`$TP_PERM\` |
| Shell user groups | \`$(id)\` |
| EVIOCGRAB on touchpad | $GRAB |
EOF

sec "Build properties"
run "getprop | grep -E 'ro\.(build|product|soc|board|hardware|vendor\.build)\.' | grep -vE 'serial|\.date\]'"

sec "Accounts"
run "dumpsys account | sed -n '1,/Accounts History/p'"

sec "HOME"
run "cmd package resolve-activity --brief -a android.intent.action.MAIN -c android.intent.category.HOME"
run "cmd package query-activities --brief -a android.intent.action.MAIN -c android.intent.category.HOME"

sec "Graphics"
run "dumpsys SurfaceFlinger | grep -i gles"
run "pm list features | grep -iE 'vulkan|opengles'"
run "getprop | grep -E 'ro\.hardware\.(egl|vulkan)|ro\.hwui\.use_vulkan|ro\.opengles\.version'"

sec "Display modes"
run "dumpsys display 2>/dev/null | grep -m1 -o 'supportedModes .*' | sed 's/}, {/}\n{/g' | grep -o 'id=[0-9]*, width=[0-9]*, height=[0-9]*, fps=[0-9.]*'"
run "dumpsys display 2>/dev/null | grep -E 'mActiveModeId|mDefaultModeId|mUserPreferredModeId' | sort -u"
run "wm size; wm density"

sec "Network"
run "ip -o -4 addr"
run "ip -o link | grep -E 'eth0|wlan0' | cut -d'\\' -f1"
run "dumpsys connectivity 2>/dev/null | grep -E 'Active default network|^ *NetworkAgentInfo\{' | cut -c1-160"
run "settings get global adb_wifi_enabled; getprop service.adb.tcp.port; getprop persist.adb.tcp.port; getprop service.adb.tls.port"

sec "Input devices (getevent -lp)"
run "ls -l /dev/input"
run "getevent -lp"

sec "DS4 touchpad probe (onnshell-evprobe)"
printf '```\n%s\n```\n' "$EV"

sec "Bluetooth bonded devices"
run "dumpsys bluetooth_manager | sed -n '/Bonded devices:/,/^ *$/p'"

sec "Packages (pm list packages -d), disabled"
run "pm list packages -d | sort"

sec "Packages (pm list packages -f)"
run "pm list packages -f | sort -t= -k2"
